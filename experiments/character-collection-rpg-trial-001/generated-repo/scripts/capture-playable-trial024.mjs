import { chromium } from '@playwright/test';
import { mkdirSync } from 'node:fs';
import { resolve } from 'node:path';

const root = resolve(process.cwd(), '../../..');
const playable = `file://${resolve(root, 'playables/sagaforge-app/index.html')}`;
const outDir = resolve(root, 'assets');
mkdirSync(outDir, { recursive: true });
const browser = await chromium.launch({ headless: true });
const page = await browser.newPage({ viewport: { width: 430, height: 920 }, deviceScaleFactor: 1 });
const errors = [];
page.on('pageerror', e => errors.push(e.message));
await page.goto(playable);
await page.waitForSelector('text=周回作戦ボード');
await page.screenshot({ path: resolve(outDir, '2026-07-04-character-collection-rpg-trial-024-home-ops.png'), fullPage: true });
await page.getByRole('button', { name: '編成' }).click();
await page.waitForSelector('text=被弾予測 / 位置役割');
await page.getByRole('button', { name: '周回' }).click();
await page.getByRole('button', { name: '選択クエストへ出撃' }).click();
await page.waitForSelector('text=AUTO判断');
await page.getByRole('button', { name: /AUTO判断/ }).click();
await page.waitForSelector('text=AUTO判断開始');
await page.screenshot({ path: resolve(outDir, '2026-07-04-character-collection-rpg-trial-024-battle-auto.png'), fullPage: true });
const positionText = await page.locator('#positionHp').innerText();
const logText = await page.locator('#logs').innerText();
await page.getByRole('button', { name: '召喚' }).click();
await page.waitForSelector('text=交換Pt / 天井風ゲージ');
await page.getByRole('button', { name: '10連スタイル召喚' }).click();
await page.screenshot({ path: resolve(outDir, '2026-07-04-character-collection-rpg-trial-024-gacha-pity.png'), fullPage: true });
const pityText = await page.locator('#pityText').innerText();
await browser.close();
if (errors.length) throw new Error(errors.join('\n'));
console.log(JSON.stringify({ ok: true, positionText, hasAutoLog: /AUTO判断開始/.test(logText), pityText }, null, 2));
