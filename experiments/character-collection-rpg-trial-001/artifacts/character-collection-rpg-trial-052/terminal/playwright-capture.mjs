import { spawn } from 'node:child_process';
import { mkdirSync } from 'node:fs';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const repo = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../../../../..');
const gen = path.join(repo, 'experiments/character-collection-rpg-trial-001/generated-repo/package.json');
const require = createRequire(gen);
const { chromium } = require('@playwright/test');
const out = path.join(repo, 'assets');
mkdirSync(out, { recursive: true });
const server = spawn('python3', ['-m', 'http.server', '4176', '--bind', '127.0.0.1'], { cwd: repo, stdio: ['ignore', 'pipe', 'pipe'] });
await new Promise((resolve) => setTimeout(resolve, 800));
const browser = await chromium.launch({ headless: true });
const page = await browser.newPage({ viewport: { width: 430, height: 920 }, deviceScaleFactor: 1 });
const url = 'http://127.0.0.1:4176/playables/sagaforge-app/index.html';
await page.goto(url, { waitUntil: 'networkidle' });
await page.locator('#questIntentHome').scrollIntoViewIfNeeded();
await page.screenshot({ path: path.join(out, '2026-07-08-character-collection-rpg-trial-052-home-intent.png'), fullPage: true });
const homeVisible = await page.locator('#questIntentHome').innerText();
await page.getByRole('button', { name: 'クエストで確認' }).click();
await page.locator('#questIntentQuest').scrollIntoViewIfNeeded();
await page.screenshot({ path: path.join(out, '2026-07-08-character-collection-rpg-trial-052-quest-intent.png'), fullPage: true });
await page.getByRole('button', { name: 'Round別予約を作って戦闘へ' }).first().click();
await page.locator('#questIntentBattle').scrollIntoViewIfNeeded();
await page.screenshot({ path: path.join(out, '2026-07-08-character-collection-rpg-trial-052-battle-intent.png'), fullPage: true });
const battleVisible = await page.locator('#questIntentBattle').innerText();
await page.getByRole('button', { name: '予約ターン実行' }).click();
await page.locator('#turnResolveBoard').scrollIntoViewIfNeeded();
await page.screenshot({ path: path.join(out, '2026-07-08-character-collection-rpg-trial-052-turn-resolve.png'), fullPage: true });
const resolveText = await page.locator('#turnResolveBoard').innerText();
console.log(JSON.stringify({ url, home_has_round: homeVisible.includes('Round 1'), battle_has_final: battleVisible.includes('最終Round'), turn_resolved: resolveText.includes('Hit'), title: await page.title() }, null, 2));
await browser.close();
server.kill('SIGTERM');
